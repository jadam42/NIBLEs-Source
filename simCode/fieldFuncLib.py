def RF_Sinc(t, index, Params):
    """
    Function calculates an ideal Sinc RF waveform in the lab reference frame. Can be used to 
    generate a constant amplitude RF pulse by setting nLobes = -1

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector 
    being simulated
    Params = Parameter tuple where each element is the following:
		Params[0] = Duration of RF pulse; Experiment.Duration
		Params[1] = RF field amplitude expressed as a 3 element Numpy Aray; Experiment.B1
		Params[2] = Carrier frequency of the RF pulse; Experiment.Larmor+ Experiment.dOmega
		Params[3] = Phase factor of RF pulse; Experiment.Phi
		Params[4] = Number of lobes in Sinc pulse waveform; Experiment.nLobes

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    # Calculate RF waveform

    Amp = np.sinc(((Params[4]+ 1)/Params[0])*(t- Params[0]/2))

    # Calculate full RF field
    RFx = Amp* Params[1]* np.cos(Params[2]*t+ Params[3])
    RFy = -Amp* Params[1]* np.sin(Params[2]*t+ Params[3])
    RFz = 0

    return np.array([RFx, RFy, RFz], dtype = float)

def RF_WinSinc_Hanning(t, index, Params):
    """
    Function calculates a Hanning windowed RF waveform in the lab reference frame.

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector 
    being simulated
    Params = Parameter tuple where each element is the following:
		Params[0] = Duration of RF pulse; Experiment.Duration
		Params[1] = RF field amplitude expressed as a 3 element Numpy Aray; Experiment.B1
		Params[2] = Carrier frequency of the RF pulse; Experiment.Larmor+ Experiment.dOmega
		Params[3] = Phase factor of RF pulse; Experiment.Phi
		Params[4] = Number of lobes in Sinc pulse waveform; Experiment.nLobes

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    # Calculate RF waveform
    Amp = np.sinc(((Params[4]+ 1)/Params[0])*(t- Params[0]/2))* ...
    (0.5+ 0.5*np.cos(np.pi*(1/Params[0])*(t- Params[0]/2)))

    # Calculate full RF field
    RFx = Amp* Params[1]* np.cos(Params[2]*t+ Params[3])
    RFy = -Amp* Params[1]* np.sin(Params[2]*t+ Params[3])
    RFz = 0

    return np.array([RFx, RFy, RFz], dtype = float)

