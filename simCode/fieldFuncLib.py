def RxUniform(t, index, Params):
    """
    Function returns a receive coil sensitivity of 1 across the entire imaging volume.

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector being simulated
    Params = Unused placeholder variable

    Returns:
    Floating point number denoting the relative sensitivity of the receive coil
    """
    return 1

