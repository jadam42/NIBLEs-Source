#~~~~~ Gradient Fields ~~~~~#

def Grad_IdealSquare(t, index, Params):
    """
    Function calculates an ideal square gradient waveform as a function of position 
    within the imaging volume.

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector 
    being simulated
    Params = Parameter tuple where each element is the following:
	    Params[0] = Numpy 4D array containing positions of all vectors; Experiment.MPosition
	    Params[1] = Maximum amplitude of gradient, expressed as a 3 element NumPy array;
            Experiment.gradAmp
	    Params[2] = Dimensions of the imaging volume in metric; Experiment.sizeMetric

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    # Calculate max gradient amplitude at vector position
    Position = Params[0][index]
    positionalAmplitude = Params[1]*(Position- Params[2]/2)

    Bgrad = np.array([0, 0, np.sum(positionalAmplitude)])        

    return Bgrad

def Grad_IdealTrapezoid(t, index, Params):
    """
    Function calculates an ideal trapezoid gradient as a function of position within the imaging volume, 
    where the gradient linearly increases from 0 to max amplitude over Experiment.riseTime at the 
    beginning of the gradient, remains constant until it reaches Experiment.Duration- Experiment.riseTime, 
    and finally linearly decreases back to zero.

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector being simulated
    Params = Parameter tuple where each element is the following:
        Params[0] = Numpy 4D array containing positions of all vectors; Experiment.MPosition
        Params[1] = Maximum amplitude of gradient, expressed as a 3 element NumPy array; Experiment.gradAmp
        Params[2] = Dimensions of the imaging volume in metric; Experiment.sizeMetric
        Params[3] = Duration of gradient waveform; Experiment.Duration
        Params[4] = Rise time of gradient; Experiment.riseTime

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    # Calculate max gradient amplitude at vector position
    Position = Params[0][index]
    positionalAmplitude = Params[1]*(Position- Params[2]/2)

    # Calculate slope of gradient
    slewRate = positionalAmplitude/Params[4]

    # Identify where in the trapezoid simulation is happeneing, then calculate appropriate field
    if t < Params[4]:
        Amp = slewRate*t
    elif Params[4] <= t <= (Params[3]- Params[4]):
        Amp = positionalAmplitude
    elif t > (Params[3]- Params[4]):
        Amp = positionalAmplitude - slewRate*(t- (Params[3]- Params[4]))

    Bgrad = np.array([0, 0, np.sum(Amp)])

    return Bgrad

def Grad_IdealRampUp(t, index, Params):
    """
    Function calculates an ideal gradient ramp as a function of position within the imaging volume, 
    where the gradient linearly increases from 0 to max amplitude over Experiment.Duration

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector being simulated
    Params = Parameter tuple where each element is the following:
        Params[0] = Numpy 4D array containing positions of all vectors; Experiment.MPosition
        Params[1] = Maximum amplitude of gradient, expressed as a 3 element NumPy array; Experiment.gradAmp
        Params[2] = Dimensions of the imaging volume in metric; Experiment.sizeMetric
        Params[3] = Duration of gradient waveform; Experiment.Duration

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    # Calculate max gradient amplitude at vector position
    Position = Params[0][index]
    positionalAmplitude = Params[1]*(Position- Params[2]/2)

    # Calculate slope of gradient
    slewRate = positionalAmplitude/Params[3]

    # Calculate gradient amplitude
    Amp = slewRate*t
    Bgrad = np.array([0, 0, np.sum(Amp)])

    return Bgrad

