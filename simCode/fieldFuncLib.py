#~~~~~ B0 Fields ~~~~~#

def IdealB0(t, index, Params):
    """
    Function 'calculates' an ideal uniform B0 by simply returning the value of Experiment.Blab +
    for a given index.

    Parameters:
    t = Time from beginning of sequence element (s)
    index = 4-element list indicating the index in Experiment.M corresponding to the vector 
    being simulated
    Params = Parameter tuple where each element is the following:
        Params[0] = Numpy 4D array containing nominal B0 field at the location of the vector being 
            evolved (T); Experiment.BLab
        Params[1] = Numpy 4D array containing field shifts calculated by T2star reproduction for 
            each vector (T); Experiment.t2starOffsets
        Params[2] = Numpy 4D array containing material-specific chemical shift for each vector (ppm); 
        Experiment.chemShift

    Returns:
    3-element Numpy array containing the x-, y-, and z- components of calculated field
    """
    return Params[0]

