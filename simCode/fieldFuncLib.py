import numpy as np

# Functions for defining the magnetic fields within the imaging volume, and receive coil sensitivity 
# within the imaging volume.
#
# To be compatible with the NIBLEs solver, magnetic field functions must follow the input format 
# func(t, index, Params), where t is the simulation time, index is the index value addressing the 
# vector being evolved in Experiment.M, and Params is a tuple containing all other information 
# required to define the desired applied field. Each function should output a magnetic field vector 
# expressed in Cartesian co-ordinates as a 3 element NumPy array of float numbers. All fields should 
# be defined in the Lab frame, as the NIBLEs solver automatically transforms given magnetic fields 
# into the rotating reference frame.
#
# t and index are both generated automatically by the solver, and do not need to be defined by an 
# end user. Params are generated by the relevant sequence element methods when the corresponding 
# field function is assigned to a non-Zero function. These Params follow standard forms. See 
# variable index for details.The parameters given for each function in this documentation are the
# elements of the relevant Params variable used by the function.
#
# Receive coil fields use the same parameter format as the magnetic field functions (t, index, Params), 
# however these functions should instead return a single value representing the relative sensitivity of 
# the coil for the specified position.
#
# Original version of this code designed and written by John Adams (jadam33@uwo.ca)
#
