def rx_uniform(t, index, params):
    """'Calculates' a uniform receive coil sensitivity across the entire
    imaging volume.

    Parameters
    ----------
    t : float
        Simulation time. Produced by solver and should not be defined by
        end user.
    index : array_like
        List indicating the index in Experiment.sample_mag corresponding
        to the vector being simulated
    params : tuple
        Parameter tuple where each element is the following:
        params[0] : array_like
            4D array containing positions of all vectors;
            Experiment.m_position
        params[1] : array_like
            Dimensions of the imaging volume in metric; 
            Experiment.size_metric
        params[2] : array_like
            Dimensions of the imaging volume in pixels; 
            Experiment.size_pixels
        params[3] : dict
            Dictionary containing any keyword arguments provided to
            Experiment using Experiment.rx_set()

    Returns
    -------
    rx_sensitivity : float
        Floating point number indicating the relative sensitivity of the
        RX coil at the specified position.
    """
    rx_sensitivity = 1
    return rx_sensitivity

