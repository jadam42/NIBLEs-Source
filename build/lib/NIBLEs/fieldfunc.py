#~~~~~ Gradient Fields ~~~~~#

def grad_ideal_square(t, index, params):
    """Calculates an ideal square gradient waveform as a function of
    position within the imaging volume.

    Parameters
    ----------
    t : float
        Simulation time. Produced by solver and should not be defined by
        end user.
    index : array_like
        List indicating the index in Experiment.sample_mag corresponding
        to the vector being simulated
    params : tuple
        Parameter tuple where each element is the following:
        params[0] : array_like
            4D array containing positions of all vectors;
            Experiment.m_position
        params[1] : array_like
            Maximum amplitude of gradient, expressed as a 
            3-element NumPy array; Experiment.grad_amp
        params[2] : array_like
            Dimensions of the imaging volume in metric; 
            Experiment.size_metric
        params[3] : float
            Duration of gradient; Experiment.duration
        params[4] : float
            Rise time of gradient waveform; Experiment.rise_time
        params[5] : dict
            Dictionary containing any keyword arguments provided to any
            of the gradient methods in Experiment (eg.
            Experiment.gradient())

    Returns
    -------
    b_grad : array_like
        3-element array defining applied gradient field as a cartesian
        vector (T).
    """

    # Calculate max gradient amplitude at vector position
    position = params[0][index]
    position_amp = params[1]*(position- params[2]/2)

    b_grad = np.array([0, 0, np.sum(position_amp)])

    return b_grad

def grad_ideal_trap(t, index, params):
    """Calculates an ideal trapezoidal gradient waveform as a function
    of position within the imaging volume.

    Gradient linearly increases from 0 to max amplitude over 
    Experiment.rise_time at the beginning of the gradient, remains
    constant until it reaches Experiment.duration- Experiment.rise_time,
    and finally linearly decreases back to zero.

    Parameters
    ----------
    t : float
        Simulation time. Produced by solver and should not be defined by
        end user.
    index : array_like
        List indicating the index in Experiment.sample_mag corresponding
        to the vector being simulated
    params : tuple
        Parameter tuple where each element is the following:
        params[0] : array_like
            4D array containing positions of all vectors;
            Experiment.m_position
        params[1] : array_like
            Maximum amplitude of gradient, expressed as a 
            3-element NumPy array; Experiment.grad_amp
        params[2] : array_like
            Dimensions of the imaging volume in metric; 
            Experiment.size_metric
        params[3] : float
            Duration of gradient; Experiment.duration
        params[4] : float
            Rise time of gradient waveform; Experiment.rise_time
        params[5] : dict
            Dictionary containing any keyword arguments provided to any
            of the gradient methods in Experiment (eg.
            Experiment.gradient())

    Returns
    -------
    b_grad : array_like
        3-element array defining applied gradient field as a cartesian
        vector (T).
    """
    # Calculate max gradient amplitude at vector position
    position = params[0][index]
    position_amp = params[1]*(position- params[2]/2)

    # Calculate slope of gradient
    slew_rate = position_amp/params[4]

    # Identify where in the trapezoid simulation is happeneing, then
    # calculate appropriate field
    if t < params[4]:
        amp = slew_rate*t
    elif params[4] <= t <= (params[3]- params[4]):
        amp = position_amp
    elif t > (params[3]- params[4]):
        amp = position_amp - slew_rate*(t- (params[3]- params[4]))

    b_grad = np.array([0, 0, np.sum(amp)])

    return b_grad

